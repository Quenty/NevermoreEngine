--!strict
--[[
	@class MetricUnit.Derived.spec.lua
]]

local require = require(script.Parent.loader).load(script)

local Jest = require("Jest")
local MetricUnit = require("MetricUnit")

local describe = Jest.Globals.describe
local expect = Jest.Globals.expect
local it = Jest.Globals.it

describe("MetricUnit prefixed base units", function()
	it("reads milliseconds and microseconds back", function()
		expect(MetricUnit.milliseconds(250):In("millisecond")).toBeCloseTo(250, 9)
		expect(MetricUnit.microseconds(40):In("microsecond")).toBeCloseTo(40, 9)
		expect(MetricUnit.milliseconds(1_500):InSeconds()).toBeCloseTo(1.5, 9)
		expect(MetricUnit.microseconds(1_000):In("millisecond")).toBeCloseTo(1, 9)
	end)

	it("keeps decimal and binary memory apart", function()
		expect(MetricUnit.gigabytes(1):In("megabyte")).toBe(1_000)
		expect(MetricUnit.kibibytes(1):In("byte")).toBe(1_024)
		expect(MetricUnit.mebibytes(4):In("byte")).toBe(4_194_304)
		expect(MetricUnit.gibibytes(1):In("mebibyte")).toBe(1_024)
		expect(MetricUnit.mebibytes(1):In("kibibyte")).toBe(1_024)
		expect(MetricUnit.gigabytes(1):In("gibibyte")).toBeCloseTo(0.9313, 4)
		expect(MetricUnit.kibibytes(1):In("kilobyte")).toBeCloseTo(1.024, 9)
	end)

	it("reads milligrams back", function()
		expect(MetricUnit.milligrams(500):In("gram")).toBeCloseTo(0.5, 9)
		expect(MetricUnit.grams(2):In("milligram")).toBeCloseTo(2_000, 9)
	end)

	it("reads a rate per minute and a frequency in hertz", function()
		expect(MetricUnit.perMinute(120):In("perSecond")).toBeCloseTo(2, 9)
		expect(MetricUnit.perSecond(1):In("perMinute")).toBeCloseTo(60, 9)
		expect(MetricUnit.hertz(60):In("hertz")).toBe(60)
		expect(MetricUnit.hertz(1) == MetricUnit.perSecond(1)).toBe(true)
		expect((1 / MetricUnit.milliseconds(20)):In("hertz")).toBeCloseTo(50, 9)
	end)
end)

describe("MetricUnit area and volume", function()
	it("reads areas back, from lengths multiplied", function()
		expect(MetricUnit.squareMeters(50):In("squareMeter")).toBe(50)
		expect(MetricUnit.hectares(1):In("squareMeter")).toBe(10_000)
		expect(MetricUnit.squareKilometers(1):In("hectare")).toBe(100)
		expect((MetricUnit.meters(100) * MetricUnit.meters(100)):In("hectare")).toBeCloseTo(1, 9)
		expect(MetricUnit.isKind(MetricUnit.kilometers(2) * MetricUnit.kilometers(3), "area")).toBe(true)
		expect((MetricUnit.kilometers(2) * MetricUnit.kilometers(3)):In("squareKilometer")).toBeCloseTo(6, 9)
	end)

	it("reads volumes back, from areas and lengths multiplied", function()
		expect(MetricUnit.liters(1):In("milliliter")).toBeCloseTo(1_000, 9)
		expect(MetricUnit.cubicMeters(1):In("liter")).toBeCloseTo(1_000, 9)
		expect(MetricUnit.milliliters(250):In("liter")).toBeCloseTo(0.25, 9)
		expect(MetricUnit.isKind(MetricUnit.pow(MetricUnit.centimeters(10), 3), "volume")).toBe(true)
		expect(MetricUnit.pow(MetricUnit.centimeters(10), 3):In("liter")).toBeCloseTo(1, 9)
		expect(MetricUnit.isKind(MetricUnit.squareMeters(2) * MetricUnit.meters(3), "volume")).toBe(true)
	end)
end)

describe("MetricUnit mechanics", function()
	it("reads speeds in m/s and km/h", function()
		expect(MetricUnit.metersPerSecond(10):In("kilometerPerHour")).toBeCloseTo(36, 9)
		expect(MetricUnit.kilometersPerHour(36):In("meterPerSecond")).toBeCloseTo(10, 9)
		expect((MetricUnit.kilometers(36) / MetricUnit.hours(1)):In("meterPerSecond")).toBeCloseTo(10, 9)
		expect(MetricUnit.isKind(MetricUnit.kilometersPerHour(1), "speed")).toBe(true)
	end)

	it("makes an acceleration from a speed over a time", function()
		local acceleration = MetricUnit.metersPerSecond(20) / MetricUnit.seconds(2)
		expect(MetricUnit.isKind(acceleration, "acceleration")).toBe(true)
		expect(acceleration:In("meterPerSecondSquared")).toBeCloseTo(10, 9)
		expect(MetricUnit.metersPerSecondSquared(9.81):In("meterPerSecondSquared")).toBe(9.81)
	end)

	it("makes a newton from a mass times an acceleration", function()
		local force = MetricUnit.kilograms(2) * MetricUnit.metersPerSecondSquared(3)
		expect(MetricUnit.isKind(force, "force")).toBe(true)
		expect(force:In("newton")).toBeCloseTo(6, 9)
		expect(force == MetricUnit.newtons(6)).toBe(true)
	end)

	it("makes energy from a force over a length, and power from energy over time", function()
		local work = MetricUnit.newtons(10) * MetricUnit.meters(5)
		expect(MetricUnit.isKind(work, "energy")).toBe(true)
		expect(work:In("joule")).toBeCloseTo(50, 9)

		local power = work / MetricUnit.seconds(2)
		expect(MetricUnit.isKind(power, "power")).toBe(true)
		expect(power:In("watt")).toBeCloseTo(25, 9)

		expect((MetricUnit.kilowatts(2) * MetricUnit.hours(3)):In("kilowattHour")).toBeCloseTo(6, 9)
		expect((MetricUnit.kilowattHours(3) / MetricUnit.hours(1)):In("kilowatt")).toBeCloseTo(3, 9)
	end)

	it("converts between energy units", function()
		expect(MetricUnit.kilojoules(1):In("joule")).toBe(1_000)
		expect(MetricUnit.kilowattHours(1):In("kilojoule")).toBe(3_600)
		expect(MetricUnit.kilocalories(1):In("joule")).toBe(4_184)
		expect(MetricUnit.joules(4_184):In("kilocalorie")).toBe(1)
	end)

	it("makes pressure from a force over an area", function()
		local pressure = MetricUnit.newtons(1_000) / MetricUnit.squareMeters(2)
		expect(MetricUnit.isKind(pressure, "pressure")).toBe(true)
		expect(pressure:In("pascal")).toBeCloseTo(500, 9)
		expect(MetricUnit.bars(1):In("kilopascal")).toBe(100)
		expect(MetricUnit.kilopascals(250):In("bar")).toBeCloseTo(2.5, 9)
	end)

	it("makes density from a mass over a volume", function()
		local density = MetricUnit.kilograms(1) / MetricUnit.liters(1)
		expect(MetricUnit.isKind(density, "density")).toBe(true)
		expect(density:In("kilogramPerCubicMeter")).toBeCloseTo(1_000, 9)
		expect(density:In("gramPerCubicCentimeter")).toBeCloseTo(1, 9)
		expect(MetricUnit.gramsPerCubicCentimeter(7.8):In("kilogramPerCubicMeter")).toBeCloseTo(7_800, 9)
		expect((MetricUnit.kilogramsPerCubicMeter(1_000) * MetricUnit.liters(2)):In("kilogram")).toBeCloseTo(2, 9)
	end)
end)

describe("MetricUnit data rates", function()
	it("makes a data rate from memory over time", function()
		local rate = MetricUnit.kilobytes(50) / MetricUnit.seconds(1)
		expect(MetricUnit.isKind(rate, "dataRate")).toBe(true)
		expect(rate:In("kilobytePerSecond")).toBeCloseTo(50, 9)
		expect(MetricUnit.bytesPerSecond(2_000):In("kilobytePerSecond")).toBe(2)
		expect((MetricUnit.kilobytesPerSecond(8) * MetricUnit.minutes(1)):In("kilobyte")).toBeCloseTo(480, 9)
	end)
end)

describe("MetricUnit derived boundaries", function()
	it("tells derived dimensions apart", function()
		expect(MetricUnit.isKind(MetricUnit.newtons(1), "energy")).toBe(false)
		expect(MetricUnit.isKind(MetricUnit.joules(1), "force")).toBe(false)
		expect(MetricUnit.isKind(MetricUnit.joules(1), "power")).toBe(false)
		expect(MetricUnit.isKind(MetricUnit.liters(1), "area")).toBe(false)
		expect(MetricUnit.isKind(MetricUnit.perSecond(1), "dataRate")).toBe(false)
		expect(MetricUnit.isKind(MetricUnit.metersPerSecondSquared(1), "speed")).toBe(false)
	end)

	it("errors when a derived reader meets another dimension, naming both", function()
		expect(function()
			MetricUnit.joules(1):In("watt")
		end).toThrow('In("watt") reads length^2·mass/time^3, not length^2·mass/time^2')
		expect(function()
			MetricUnit.newtons(1):In("pascal")
		end).toThrow('In("pascal") reads mass/length/time^2, not length·mass/time^2')
	end)

	it("expects each derived dimension by name", function()
		expect(MetricUnit.expect(MetricUnit.hectares(1), "area", "plot")).toBe(10_000)
		expect(MetricUnit.expect(MetricUnit.liters(1), "volume", "tank")).toBeCloseTo(1e-3, 12)
		expect(MetricUnit.expect(MetricUnit.metersPerSecondSquared(9.81), "acceleration", "gravity")).toBe(9.81)
		expect(MetricUnit.expect(MetricUnit.newtons(5), "force", "thrust")).toBe(5)
		expect(MetricUnit.expect(MetricUnit.kilojoules(2), "energy", "charge")).toBe(2_000)
		expect(MetricUnit.expect(MetricUnit.kilowatts(1), "power", "output")).toBe(1_000)
		expect(MetricUnit.expect(MetricUnit.bars(2), "pressure", "tyre")).toBe(200_000)
		expect(MetricUnit.expect(MetricUnit.kilogramsPerCubicMeter(997), "density", "water")).toBe(997)
		expect(MetricUnit.expect(MetricUnit.kilobytesPerSecond(1), "dataRate", "budget")).toBe(1_000)
		expect(function()
			MetricUnit.expect(MetricUnit.joules(1), "power", "output")
		end).toThrow("MetricUnit.expect: output expects length^2·mass/time^3, got length^2·mass/time^2")
	end)
end)
